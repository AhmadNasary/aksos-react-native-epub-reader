// Inlines JSZip + the engine into a single HTML document used by the WebView.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');

const jszipPath = require.resolve('jszip/dist/jszip.min.js', { paths: [root] });
const safe = (js) => js.replace(/<\/script/gi, '<\\/script');
const jszip = safe(fs.readFileSync(jszipPath, 'utf8'));
const engine = safe(fs.readFileSync(path.join(root, 'src/engine/reader.js'), 'utf8'));

const html = `<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<style>
html,body{margin:0;height:100%;overflow:hidden;-webkit-user-select:none;user-select:none;-webkit-tap-highlight-color:transparent;-webkit-touch-callout:none}
#frame{position:fixed;border:0;background:transparent}
#oldPage{position:fixed;left:0;top:0;display:block;visibility:hidden;overflow:hidden;pointer-events:none;border-radius:38px;will-change:transform,clip-path,opacity}
#ghost,#ghost2{position:absolute;border:0;background:transparent}
.lbl{position:absolute;left:0;right:0;box-sizing:border-box;padding:0 28px;text-align:center;white-space:nowrap;overflow:hidden;text-overflow:ellipsis;opacity:.5;font:13px -apple-system,Roboto,"Segoe UI",sans-serif}
#curlBox{position:fixed;left:0;top:0;display:block;visibility:hidden;overflow:hidden;pointer-events:none}
#flap{position:absolute;left:0;top:0;transform-origin:0 0;filter:drop-shadow(0 0 10px rgba(0,0,0,.45));will-change:transform}
#flapClip,#flapBack{position:absolute;left:0;top:0;border:0}
#flapClip{overflow:hidden;border-radius:38px;will-change:clip-path}
#foldShade{position:absolute;left:0;top:0;transform-origin:0 0;display:none}
#hdr,#ftr{position:fixed;left:0;right:0;box-sizing:border-box;padding:0 28px;text-align:center;white-space:nowrap;overflow:hidden;text-overflow:ellipsis;pointer-events:none;opacity:.5;font:13px -apple-system,Roboto,"Segoe UI",sans-serif}
#hdr{top:20px}#ftr{bottom:20px}
</style></head>
<body><div id="hdr"></div><iframe id="frame"></iframe><div id="oldPage"><iframe id="ghost"></iframe></div><div id="curlBox"><div id="flap"><div id="flapClip"><div id="flapBack"></div><iframe id="ghost2"></iframe></div></div><div id="foldShade"></div></div><div id="ftr"></div>
<script>${jszip}</script>
<script>${engine}</script>
</body></html>`;

fs.writeFileSync(
  path.join(root, 'src/engine/html.ts'),
  '// GENERATED by scripts/build-engine.js - do not edit.\nexport const READER_HTML: string = ' + JSON.stringify(html) + ';\n'
);
fs.mkdirSync(path.join(root, 'test'), { recursive: true });
fs.writeFileSync(path.join(root, 'test/reader.html'), html);
console.log('engine built:', (html.length / 1024).toFixed(0) + ' KB');
